"""Writes ak820-agent/tests/lockchan_parity.rs: the reference encoder's
(scripts/lockchan.py) output over fixed cases, which the Rust port must
reproduce byte for byte. lockchan.py stays the oracle; never hand-edit the
generated file, rerun this.

    python scripts/gen_lockchan_vectors.py
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from lockchan import encode, P0, P1, P2, P3, PROFILES  # noqa: E402

OUT = os.path.join(HERE, "..", "ak820-agent", "tests", "lockchan_parity.rs")
LENGTHS = (0, 1, 2, 3, 4, 7, 8, 13, 20, 29, 37, 42, 47, 48)


def cases():
    rng = random.Random(820)
    for profile in (P0, P1, P2, P3):
        for n in LENGTHS:
            for user in (0x00, 0x02, rng.randrange(8)):
                payload = bytes(rng.randrange(256) for _ in range(n))
                kind, seq = rng.randrange(16), rng.randrange(256)
                yield profile, kind, seq, user, payload
        # Edge values: all-zero and all-ones payloads, the largest type and seq.
        for payload in (bytes(48), b"\xff" * 48, b"\xff" * 5):
            yield profile, 15, 255, 0x07, payload
        yield profile, 0, 0, 0x00, b"Cosmic Cadet - Europa - The Adventure"[:42]
        # Every user baseline (codex, sender design, 17).
        for user in range(8):
            yield profile, 1, user, user, bytes(rng.randrange(256) for _ in range(13))
        # Both trailer branches: searched for, since a payload ending on the
        # first trailer bit is rare in some profiles.
        for second in (False, True):
            for _ in range(20000):
                payload = bytes(rng.randrange(256) for _ in range(rng.randrange(1, 49)))
                w = encode(payload, type=3, seq=7, profile=profile, user=0x00)
                if ((w[-2] ^ w[-1]) & PROFILES[profile][5][0] != 0) != second:
                    yield profile, 3, 7, 0x00, payload
                    break


def main():
    rows, branches = [], set()
    for profile, kind, seq, user, payload in cases():
        w = encode(payload, type=kind, seq=seq, profile=profile, user=user)
        # Which trailer branch: the first trailer write flips the profile's
        # first trailer bit, or (when the payload already ended there) its second.
        ta = PROFILES[profile][5][0]
        branches.add((profile, (w[-2] ^ w[-1]) & ta != 0))
        rows.append(f'    ({profile}, {kind}, {seq}, 0x{user:02x}, "{payload.hex()}", "{bytes(w).hex()}"),')
    missing = {(p, t) for p in (P0, P1, P2, P3) for t in (True, False)} - branches
    if missing:
        sys.exit(f"the cases miss trailer branches {sorted(missing)}: add cases")
    src = "\n".join([
        "//! GENERATED by scripts/gen_lockchan_vectors.py from scripts/lockchan.py -- do not edit.",
        "//! The Rust encoder must reproduce the reference encoder's writes byte for byte.",
        "",
        "use ak820_agent::lockchan::{encode, Profile};",
        "",
        "/// (profile, type, seq, user, payload hex, writes hex)",
        "const CASES: &[(u8, u8, u8, u8, &str, &str)] = &[",
        *rows,
        "];",
        "",
        "fn hex(s: &str) -> Vec<u8> {",
        "    (0..s.len()).step_by(2).map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap()).collect()",
        "}",
        "",
        "#[test]",
        "fn the_rust_encoder_matches_lockchan_py() {",
        "    for (i, &(p, kind, seq, user, payload, writes)) in CASES.iter().enumerate() {",
        "        let profile = [Profile::P0, Profile::P1, Profile::P2, Profile::P3][p as usize];",
        "        let got = encode(&hex(payload), kind, seq, profile, user).unwrap();",
        "        assert_eq!(got, hex(writes), \"case {i}: P{p} type {kind} seq {seq} user {user:#04x} payload {payload}\");",
        "    }",
        f"    assert_eq!(CASES.len(), {len(rows)});",
        "}",
        "",
    ])
    with open(OUT, "w", newline="\n") as f:
        f.write(src)
    print(f"wrote {len(rows)} cases to {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
